/**
 * Класс LinkedList<T>
 * наследник инттерфейса List
 * отвечает за реализацию двунаправленного связаного списка.
 *
 * односвязанный список - каждый элемент такого списка содержит данные и ссылка не следуюзий элемент
 * между элементами образуется связь. У нее одно направление - от начала к концу списка.
 * Последний элемент ни начто не ссылается
 * Связка из данных и ссылки называется узлом. Первый элемент ссылка - голова.
 *
 * Двунаправленный связный список отличается от односвязанного тем
 * что каждый узел ссылается не только на следующий, но и на предыдуший.
 * Помимо головы выделяют хвост - последний узел списка
 * У головы нет ссылки на предыдуший элемента, а у хвоста нет ссылки на следующий
 *
 * По сравнению с ArrayList<T>, список LinkedList<T> дополнительно наследует
 * от абстрактного класса AbstractSequentialList<T>. Этот класс отвечает за реализацию списка,
 * где элементы хранятся в определенной последовательности.
 * LinkedList<T> наследует основной способ использования AbstractSequentialList<T> -
 * последовательный обход элементов друг за другом. Поскольку LinkedList<T> двунаправленный список -
 * его операции могут применяться с двух сторон - с начала или с конца.
 *
 * Метод addFirst(T) добавляет элементы в начало списка
 * Метод addLast(T) добавляет элемент в конец списка
 * Обе операции предоставляют собой перемещение двух ссылок.
 * При добавлении в начало, экс-головной узел начинает ссылаться на новую голову,
 * а в поле head записывается ссылка на новый элемент. Аналогично происходит и с добавлением в конец
 *
 *  removeFirst() и removeLast()
 *  Операции удаления из начала и конца списка.
 *
 *  getFirst() - getLast()
 *  Получить первый и последний элемент списка LinkedList<T>
 *
 *  add(int, T), remove(int) и get(int)
 *  добавление, удаление и получение элемента по индексу.
 *  При добавление и удаление так же происходит перепривязка ссылок двух соседних элементов
 *
 */


