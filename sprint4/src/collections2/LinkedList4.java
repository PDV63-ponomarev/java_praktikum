// односвязный список
// для элементов-узлов создается класс Node<T>
// где T будет обозначатся тип данных внутри списка
// у Node<T> будет ва поля. для данных внутри элемента - T data и для ссылки - Node<T> next
// для самого списка - класс SinglyLinkedList<T>. У него также будет два поля.
// Для головного элемента Node<T> head,  и для длины списка int size

class SinglyLinkedList<T>{
    public Node<T> head;
    private int size = 0;
}
class Node<T>{
    public T data;
    public Node<T> next;

    public Node (T data){
        this.data = data;
        this.next = null;
    }
}

// чтобы реализовать двусвязный список, нужно добавить в класс элемента Node2<T>
// поле для ссылки на предыдуший узел - Node2<T> prev,
// а в класс списка DoublyLinkedList<T> поля для хвоста Node2<T> tail

class DoublyLinkedList<T>{
    public Node2<T> head;
    public Node2<T> tail;
    private int size = 0;
}
class Node2<T>{
    public T data;
    public Node2<T> next;
    public Node2<T> prev;

    public Node2 (T data){
        this.data = data;
        this.next = null;
        this.prev = null;
    }
}